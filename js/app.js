function updateOrderMargin() {
  var qty = parseFloat(document.getElementById('kite-ord-qty').value) || 1;
  var price = parseFloat(document.getElementById('kite-ord-price').value) || 0;
  var prodRadios = document.getElementsByName('kite-prod');
  var isMis = true;
  for (var i = 0; i < prodRadios.length; i++) {
    if (prodRadios[i].checked && prodRadios[i].value === 'CNC') isMis = false;
  }
  var val = qty * price;
  var reqMargin = isMis ? val * 0.2 : val;
  var estCharges = isMis ? Math.min(20, val * 0.0003) + val * 0.0001 : val * 0.0011;
  document.getElementById('kite-req-margin').textContent = formatINR(reqMargin, 2);
  document.getElementById('kite-est-charges').textContent = formatINR(estCharges, 2);
}

function submitKiteOrder() {
  if (killSwitchDisabled) {
    showToast('Order blocked: Kill Switch is active! Re-enable segments in Holdings.');
    return;
  }
  var qty = parseInt(document.getElementById('kite-ord-qty').value, 10) || 1;
  var price = parseFloat(document.getElementById('kite-ord-price').value) || 0;
  var prodRadios = document.getElementsByName('kite-prod');
  var prod = 'MIS';
  for (var i = 0; i < prodRadios.length; i++) {
    if (prodRadios[i].checked) prod = prodRadios[i].value;
  }
  var now = new Date();
  var timeStr = now.toTimeString().split(' ')[0];
  KITE_ORDERS.unshift({
    time: timeStr,
    side: activeOrderSide,
    sym: activeWatchlistSymbol,
    prod: prod,
    qty: qty,
    price: price,
    status: 'COMPLETE'
  });
  document.getElementById('kite-order-count').textContent = String(KITE_ORDERS.length);
  renderKiteOrders();
  showToast(activeOrderSide + ' ' + qty + ' ' + activeWatchlistSymbol + ' @ ₹' + price.toFixed(2) + ' executed on NSE!');
}

