function initOrUpdateKiteChart() {
  var canvas = document.getElementById('kite-price-chart');
  if (!canvas || typeof Chart === 'undefined') return;
  var st = findStock(activeWatchlistSymbol);
  var labels = ['09:15', '10:00', '10:45', '11:30', '12:15', '13:00', '13:45', '14:30', '15:30'];
  var mult = activeTimeframe === '1D' ? 1 : (activeTimeframe === '1W' ? 1.02 : (activeTimeframe === '1M' ? 1.05 : 1.12));
  var dataPts = [];
  for (var i = 0; i < st.series.length; i++) {
    dataPts.push(Number((st.series[i] * mult).toFixed(2)));
  }
  dataPts[dataPts.length - 1] = st.ltp;

  var isUp = st.chg >= 0;
  var lineColor = isUp ? '#16a34a' : '#dc2626';
  var bgColor = isUp ? 'rgba(22, 163, 74, 0.10)' : 'rgba(220, 38, 38, 0.10)';

  if (kiteChartInstance) {
    kiteChartInstance.data.labels = labels;
    kiteChartInstance.data.datasets[0].label = st.sym + ' (' + activeTimeframe + ')';
    kiteChartInstance.data.datasets[0].data = dataPts;
    kiteChartInstance.data.datasets[0].borderColor = lineColor;
    kiteChartInstance.data.datasets[0].backgroundColor = bgColor;
    kiteChartInstance.update();
    return;
  }

  kiteChartInstance = new Chart(canvas.getContext('2d'), {
    type: 'line',
    data: {
      labels: labels,
      datasets: [{
        label: st.sym + ' (' + activeTimeframe + ')',
        data: dataPts,
        borderColor: lineColor,
        backgroundColor: bgColor,
        borderWidth: 2,
        pointRadius: 2.5,
        fill: true,
        tension: 0.28
      }]
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: { display: true, labels: { boxWidth: 12, font: { size: 11 } } }
      },
      scales: {
        x: { grid: { display: false } },
        y: { grid: { color: '#f1f5f9' } }
      }
    }
  });
}

