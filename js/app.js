function switchKiteTab(tab) {
  var tabs = ['chart', 'orders', 'holdings', 'funds'];
  for (var i = 0; i < tabs.length; i++) {
    var view = document.getElementById('kite-view-' + tabs[i]);
    var btn = document.getElementById('ktab-' + tabs[i]);
    if (view) {
      if (tabs[i] === tab) view.classList.remove('hidden');
      else view.classList.add('hidden');
    }
    if (btn) {
      if (tabs[i] === tab) {
        btn.className = 'px-3 py-1.5 rounded bg-orange-50 text-[#ff5722]';
      } else {
        btn.className = 'px-3 py-1.5 rounded text-[#666666] hover:bg-slate-100';
      }
    }
  }
}

function findStock(sym) {
  for (var i = 0; i < WATCHLIST_DATA.length; i++) {
    if (WATCHLIST_DATA[i].sym === sym) return WATCHLIST_DATA[i];
  }
  return WATCHLIST_DATA[0];
}

function renderWatchlist() {
  var container = document.getElementById('kite-watchlist-container');
  var searchEl = document.getElementById('kite-wl-search');
  if (!container) return;
  var q = searchEl ? searchEl.value.toLowerCase().trim() : '';

  var html = '';
  var count = 0;
  for (var i = 0; i < WATCHLIST_DATA.length; i++) {
    var item = WATCHLIST_DATA[i];
    if (q && item.sym.toLowerCase().indexOf(q) === -1 && item.name.toLowerCase().indexOf(q) === -1) {
      continue;
    }
    count++;
    var isUp = item.chg >= 0;
    var isSelected = item.sym === activeWatchlistSymbol;
    html += '<div class="watchlist-row px-3 py-2.5 flex items-center justify-between hover:bg-slate-50 transition cursor-pointer ' + (isSelected ? 'bg-blue-50/40' : '') + '" onclick="selectWatchlistStock(\'' + item.sym + '\')">' +
      '<div>' +
      '<div class="text-xs font-semibold ' + (isUp ? 'text-[#424242]' : 'text-rose-600') + '">' + item.sym + '</div>' +
      '<div class="text-[10px] text-[#9b9b9b] truncate max-w-[140px]">' + item.name + '</div>' +
      '</div>' +
      '<div class="flex items-center gap-2">' +
      '<div class="wl-actions items-center gap-1 mr-1">' +
      '<button type="button" onclick="event.stopPropagation(); selectWatchlistStock(\'' + item.sym + '\'); openOrderPad(\'BUY\')" class="w-6 h-6 rounded bg-[#387ed1] text-white text-[10px] font-bold">B</button>' +
      '<button type="button" onclick="event.stopPropagation(); selectWatchlistStock(\'' + item.sym + '\'); openOrderPad(\'SELL\')" class="w-6 h-6 rounded bg-[#ff5722] text-white text-[10px] font-bold">S</button>' +
      '<button type="button" onclick="event.stopPropagation(); selectWatchlistStock(\'' + item.sym + '\'); renderDepthTable(\'' + item.sym + '\')" class="px-1.5 h-6 rounded bg-slate-200 text-[#424242] text-[10px] font-semibold">D</button>' +
      '</div>' +
      '<div class="text-right font-mono">' +
      '<div class="text-xs font-semibold ' + (isUp ? 'text-emerald-600' : 'text-rose-600') + '">' + item.ltp.toFixed(2) + '</div>' +
      '<div class="text-[10px] text-[#666666]">' + (isUp ? '+' : '') + item.pct.toFixed(2) + '%</div>' +
      '</div>' +
      '</div>' +
      '</div>';
  }
  container.innerHTML = html;
  var countEl = document.getElementById('kite-wl-count');
  if (countEl) countEl.textContent = count + ' / 50';
}

function renderDepthTable(sym) {
  var st = findStock(sym);
  var symEl = document.getElementById('depth-symbol');
  if (symEl) symEl.textContent = st.sym;
  var bidsEl = document.getElementById('depth-bids-list');
  var asksEl = document.getElementById('depth-asks-list');
  if (!bidsEl || !asksEl) return;

  var bHtml = '';
  var aHtml = '';
  for (var i = 1; i <= 5; i++) {
    var bidP = (st.ltp - i * 0.25).toFixed(2);
    var askP = (st.ltp + i * 0.25).toFixed(2);
    var bOrders = i * 3 + 2;
    var aOrders = i * 4 + 1;
    var bQty = i * 140 + 35;
    var aQty = i * 125 + 50;
    bHtml += '<div class="flex justify-between"><span>' + bidP + '</span><span>' + bOrders + '</span><span>' + bQty + '</span></div>';
    aHtml += '<div class="flex justify-between"><span>' + askP + '</span><span>' + aOrders + '</span><span>' + aQty + '</span></div>';
  }
  bidsEl.innerHTML = bHtml;
  asksEl.innerHTML = aHtml;
}

