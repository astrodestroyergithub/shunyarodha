function switchView(viewName) {
  var views = ['home', 'signup', 'about', 'products', 'pricing', 'varsity', 'support', 'kite'];
  for (var i = 0; i < views.length; i++) {
    var v = document.getElementById('view-' + views[i]);
    if (v) {
      if (views[i] === viewName) {
        v.classList.remove('hidden');
      } else {
        v.classList.add('hidden');
      }
    }
    var navBtn = document.getElementById('nav-' + views[i]);
    if (navBtn && views[i] !== 'kite') {
      if (views[i] === viewName) {
        navBtn.classList.add('active');
      } else {
        navBtn.classList.remove('active');
      }
    }
  }
  currentView = viewName;
  window.scrollTo({ top: 0, behavior: 'smooth' });
  if (viewName === 'kite') {
    setTimeout(function() {
      renderWatchlist();
      renderDepthTable(activeWatchlistSymbol);
      initOrUpdateKiteChart();
      renderKiteOrders();
    }, 50);
  }
}

