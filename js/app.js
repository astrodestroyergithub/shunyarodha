function updateSipCalculator() {
  var p = parseFloat(document.getElementById('sip-monthly').value) || 25000;
  var rate = parseFloat(document.getElementById('sip-rate').value) || 13;
  var years = parseFloat(document.getElementById('sip-years').value) || 15;

  document.getElementById('sip-monthly-lbl').textContent = formatINR(p, 0);
  document.getElementById('sip-rate-lbl').textContent = rate + '%';
  document.getElementById('sip-years-lbl').textContent = years + ' Years';

  var n = years * 12;
  var rDirect = (rate / 100) / 12;
  var rRegular = ((rate - 1.0) / 100) / 12;

  var invested = p * n;
  var corpusDirect = p * ((Math.pow(1 + rDirect, n) - 1) / rDirect) * (1 + rDirect);
  var corpusRegular = p * ((Math.pow(1 + rRegular, n) - 1) / rRegular) * (1 + rRegular);
  var saved = Math.max(0, corpusDirect - corpusRegular);

  document.getElementById('sip-res-invested').textContent = formatINR(invested, 0);
  document.getElementById('sip-res-corpus').textContent = formatINR(corpusDirect, 0);
  document.getElementById('sip-res-saved').textContent = '+' + formatINR(saved, 0) + ' extra stays in your demat';
}

