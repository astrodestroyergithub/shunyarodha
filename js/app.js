function updateBrokerageCalc() {
  var buy = parseFloat(document.getElementById('calc-buy').value) || 0;
  var sell = parseFloat(document.getElementById('calc-sell').value) || 0;
  var qty = parseFloat(document.getElementById('calc-qty').value) || 1;
  var isNse = document.getElementById('calc-ex-nse').checked;

  document.getElementById('calc-buy-label').textContent = '₹' + buy.toLocaleString('en-IN');
  document.getElementById('calc-sell-label').textContent = '₹' + sell.toLocaleString('en-IN');
  document.getElementById('calc-qty-label').textContent = qty.toLocaleString('en-IN');

  var buyVal = buy * qty;
  var sellVal = sell * qty;
  var turnover = buyVal + sellVal;
  var grossPnl = sellVal - buyVal;

  var brokerage = 0;
  var stt = 0;
  var exchRate = isNse ? 0.0000297 : 0.0000375;
  var stampRate = 0.00003;

  if (calcMode === 'delivery') {
    brokerage = 0;
    stt = turnover * 0.001;
    stampRate = 0.00015;
  } else if (calcMode === 'intraday') {
    var bBuy = Math.min(20, buyVal * 0.0003);
    var bSell = Math.min(20, sellVal * 0.0003);
    brokerage = bBuy + bSell;
    stt = sellVal * 0.00025;
    stampRate = 0.00003;
  } else if (calcMode === 'futures') {
    var fBuy = Math.min(20, buyVal * 0.0003);
    var fSell = Math.min(20, sellVal * 0.0003);
    brokerage = fBuy + fSell;
    stt = sellVal * 0.0002;
    exchRate = 0.0000173;
    stampRate = 0.00002;
  } else {
    brokerage = 40;
    stt = sellVal * 0.001;
    exchRate = 0.0003503;
    stampRate = 0.00003;
  }

  var exchCharges = turnover * exchRate;
  var sebiCharges = turnover * 0.000001;
  var gst = 0.18 * (brokerage + exchCharges + sebiCharges);
  var stamp = buyVal * stampRate;
  var totalCharges = brokerage + stt + exchCharges + sebiCharges + gst + stamp;
  var netPnl = grossPnl - totalCharges;
  var breakeven = qty > 0 ? totalCharges / qty : 0;

  document.getElementById('res-turnover').textContent = formatINR(turnover, 2);
  document.getElementById('res-total-charges').textContent = formatINR(totalCharges, 2);
  var netEl = document.getElementById('res-net-pnl');
  netEl.textContent = (netPnl >= 0 ? '+' : '') + formatINR(netPnl, 2);
  netEl.className = 'text-base sm:text-lg font-bold font-mono ' + (netPnl >= 0 ? 'text-emerald-600' : 'text-rose-600');

  document.getElementById('res-brokerage').textContent = formatINR(brokerage, 2);
  document.getElementById('res-stt').textContent = formatINR(stt, 2);
  document.getElementById('res-exch').textContent = formatINR(exchCharges, 2);
  document.getElementById('res-sebi').textContent = formatINR(sebiCharges, 2);
  document.getElementById('res-gst').textContent = formatINR(gst, 2);
  document.getElementById('res-stamp').textContent = formatINR(stamp, 2);
  document.getElementById('res-breakeven').textContent = formatINR(breakeven, 2) + ' / unit';
}

